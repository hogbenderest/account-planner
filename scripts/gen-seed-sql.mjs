// Generates scripts/seed.sql from src/seed/acme-corp.json.
// The generated SQL is idempotent (INSERT OR IGNORE) with fixed IDs, and is
// safe to apply to both the local (miniflare) and remote D1 databases via:
//   pnpm exec cf d1 execute account-planner-db --local  --file scripts/seed.sql
//   pnpm exec cf d1 execute account-planner-db --remote --file scripts/seed.sql
// Ownership: the seeded demo account belongs to SEED_OWNER_EMAIL below.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const SEED_OWNER_EMAIL = process.argv[2] ?? "demo@example.com";
const seed = JSON.parse(readFileSync(new URL("../src/seed/acme-corp.json", import.meta.url), "utf8"));

const lit = (v) => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  return "'" + String(v).replace(/'/g, "''") + "'";
};
const jsonLit = (v) => lit(v === null || v === undefined || v.length === 0 ? "[]" : JSON.stringify(v));
const d = new Date().toISOString();

const statements = [
  "INSERT OR IGNORE INTO pursuits (id, owner_email, account_name, parent_account, lead_salesperson, " +
  "salesperson_email, team_members, phase, proposed_offering, deal_size, close_date, " +
  "analysis_date_current, analysis_date_last, analysis_date_prior, created_at, updated_at) VALUES ('acme-pursuit', " +
    [SEED_OWNER_EMAIL, seed.pursuit.accountName, seed.pursuit.parentAccount, seed.pursuit.leadSalesperson,
     seed.pursuit.salespersonEmail, seed.pursuit.teamMembers, seed.pursuit.phase, seed.pursuit.proposedOffering,
     seed.pursuit.dealSize, seed.pursuit.closeDate, seed.pursuit.analysisDateCurrent, seed.pursuit.analysisDateLast,
     seed.pursuit.analysisDatePrior, d, d].map(lit).join(", ") + ");",
];

for (const q of seed.qualSnapshots) {
  statements.push(
    "INSERT OR IGNORE INTO qual_snapshots (id, pursuit_id, slot, analysis_date, should_scores, should_evidence, can_scores, can_evidence) " +
    `VALUES ('acme-qual-${q.slot}', 'acme-pursuit', ${q.slot}, ${lit(q.analysisDate)}, ${jsonLit(q.shouldScores)}, ${jsonLit(q.shouldEvidence)}, ${jsonLit(q.canScores)}, ${jsonLit(q.canEvidence)});`,
  );
}
for (const p of seed.profilerSnapshots) {
  statements.push(
    "INSERT OR IGNORE INTO profiler_snapshots (id, pursuit_id, slot, analysis_date, scores, evidence) " +
    `VALUES ('acme-prof-${p.slot}', 'acme-pursuit', ${p.slot}, ${lit(p.analysisDate)}, ${jsonLit(p.scores)}, ${jsonLit(p.evidence)});`,
  );
}
for (const v of seed.vulnerabilityActions) {
  statements.push(
    "INSERT OR IGNORE INTO vulnerability_actions (pursuit_id, category, current_state, desired_state, agreed_actions, owner, target_date, status) " +
    `VALUES ('acme-pursuit', ${v.category}, ${lit(v.currentState)}, ${lit(v.desiredState)}, ${lit(v.agreedActions)}, ${lit(v.owner)}, ${lit(v.targetDate)}, ${lit(v.status)});`,
  );
}

mkdirSync(new URL("../scripts/", import.meta.url), { recursive: true });
const header = [
  "-- Generated by scripts/gen-seed-sql.mjs - do not edit by hand.",
  `-- Demo account owner: ${SEED_OWNER_EMAIL}`,
  "",
];
writeFileSync(new URL("../scripts/seed.sql", import.meta.url), header.join("\n") + statements.join("\n") + "\n");
writeFileSync(new URL("../scripts/seed-batch.json", import.meta.url), JSON.stringify({ batch: statements.map((sql) => ({ sql })) }));
console.log(`wrote scripts/seed.sql + scripts/seed-batch.json (${statements.length} statements) for owner ${SEED_OWNER_EMAIL}`);
